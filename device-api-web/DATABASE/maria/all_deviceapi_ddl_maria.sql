-- 테이블 생성
CREATE TABLE COMTECOPSEQ (
    TABLE_NAME VARCHAR(20) NOT NULL,
    NEXT_ID    DECIMAL(30),
    CONSTRAINT PK_COMTECOPSEQ PRIMARY KEY (TABLE_NAME)
);

CREATE TABLE ACCELERATOR (
    SN        DECIMAL(6) NOT NULL,
    UUID      VARCHAR(50) NOT NULL,
    XAXIS     VARCHAR(20),
    YAXIS     VARCHAR(20),
    ZAXIS     VARCHAR(20),
    TIMESTAMP VARCHAR(20),
    USEYN     CHAR(1),
    CONSTRAINT PK_ACCELERATOR PRIMARY KEY (SN, UUID)
);

CREATE TABLE CONTACT_INFO (
    SN     DECIMAL(6) NOT NULL,
    NAME   CHAR(60),
    TELNO  CHAR(20),
    EMAILS VARCHAR(50),
    USEYN  CHAR(1),
    UUID   VARCHAR(50) NOT NULL,
    CONSTRAINT PK_CONTACT_INFO PRIMARY KEY (SN, UUID)
);

CREATE TABLE FILE_DETAIL_INFO (
    FILE_SN         DECIMAL(20) NOT NULL,
    FILE_STRE_COURS VARCHAR(2000),
    STRE_FILE_NM    VARCHAR(255),
    ORIGNL_FILE_NM  VARCHAR(255),
    FILE_EXTSN      VARCHAR(20),
    FILE_CN         BLOB,
    FILE_SIZE       DECIMAL(8),
    CONSTRAINT PK_FILE_DETAIL_INFO PRIMARY KEY (FILE_SN)
);

CREATE TABLE FILE_READER_WRITE (
    SN         DECIMAL(6) NOT NULL,
    UUID       VARCHAR(50) NOT NULL,
    FILE_NM    VARCHAR(255),
    FILE_TYPE  VARCHAR(40),
    UPDT_DT    DATE,
    USEYN      CHAR(1),
    FILE_SN    DECIMAL(20) NOT NULL,
    FILE_COURS VARCHAR(2000),
    FILE_SIZE  VARCHAR(40),
    CONSTRAINT PK_FILE_READER_WRITE PRIMARY KEY (SN, UUID),
    CONSTRAINT FILE_READER_WRITE_FK1 FOREIGN KEY (FILE_SN) REFERENCES FILE_DETAIL_INFO (FILE_SN)
);

CREATE TABLE MEDIA (
    SN       DECIMAL(6) NOT NULL,
    UUID     VARCHAR(50) NOT NULL,
    MD_CODE  VARCHAR(40),
    MD_SJ    VARCHAR(255),
    USEYN    CHAR(1),
    REVIV_CO VARCHAR(40),
    FILE_SN  DECIMAL(20) NOT NULL,
    CONSTRAINT PK_MEDIA PRIMARY KEY (SN, UUID),
    CONSTRAINT MEDIA_FK1 FOREIGN KEY (FILE_SN) REFERENCES FILE_DETAIL_INFO (FILE_SN)
);

CREATE TABLE DEVICE (
    SN                DECIMAL(6) NOT NULL,
    UUID              VARCHAR(50) NOT NULL,
    TELNO             VARCHAR(15),
    STRGE_INFO        VARCHAR(40),
    NTWRK_DEVICE_INFO VARCHAR(20),
    PG_VER            VARCHAR(40),
    DEVICE_NM         VARCHAR(200),
    USEYN             CHAR(1),
    OS                VARCHAR(15),
    CONSTRAINT PK_DEVICE PRIMARY KEY (SN, UUID)
);

CREATE TABLE INTERFACE_EGOV (
    SN      DECIMAL(6) NOT NULL,
    UUID    VARCHAR(50) NOT NULL,
    EMAILS  VARCHAR(50),
    USER_ID VARCHAR(20),
    USER_PW VARCHAR(2000),
    CONSTRAINT PK_INTERFACE_EGOV PRIMARY KEY (SN, UUID)
);

CREATE TABLE COMPASS (
    SN        DECIMAL(6) NOT NULL,
    UUID      VARCHAR(50) NOT NULL,
    DRC       VARCHAR(40),
    ACCRCY    VARCHAR(40),
    USEYN     CHAR(1),
    TIMESTAMP VARCHAR(20),
    CONSTRAINT PK_COMPASS PRIMARY KEY (SN, UUID)
);

CREATE TABLE GPS (
    SN     DECIMAL(6) NOT NULL,
    UUID   VARCHAR(50) NOT NULL,
    LA     VARCHAR(48),
    LO     VARCHAR(48),
    ACCRCY VARCHAR(10),
    USEYN  CHAR(1),
    CONSTRAINT PK_GPS PRIMARY KEY (SN, UUID)
);

CREATE TABLE NETWORK (
    SN         DECIMAL(6) NOT NULL,
    UUID       VARCHAR(50) NOT NULL,
    NTWRK_TYPE VARCHAR(20),
    USEYN      CHAR(1),
    CONSTRAINT PK_NETWORK PRIMARY KEY (SN, UUID)
);

CREATE TABLE PUSH_DEVICE (
    SN                DECIMAL(6) NOT NULL,
    UUID              VARCHAR(50) NOT NULL,
    NTWRK_DEVICE_INFO VARCHAR(20),
    OS_VER            VARCHAR(40),
    DEVICE_NM         VARCHAR(200),
    USEYN             CHAR(1),
    OS_TYPE           VARCHAR(15),
    TOKEN_ID          VARCHAR(500),
    CONSTRAINT PK_PUSH_DEVICE PRIMARY KEY (SN, UUID)
);

CREATE TABLE PUSH_MESSAGE (
    SN       DECIMAL(6) NOT NULL,
    UUID     VARCHAR(50) NOT NULL,
    MESSAGE  VARCHAR(2000),
    SND_DT   VARCHAR(20),
    TOKEN_ID VARCHAR(250) NOT NULL,
    CONSTRAINT PK_PUSH_MESSAGE PRIMARY KEY (SN, UUID, TOKEN_ID)
);

CREATE TABLE BARCODE_INFO (
    SN        DECIMAL(6) NOT NULL,
    UUID      VARCHAR(50),
    CODE_TYPE VARCHAR(45) NOT NULL,
    CODE_TEXT VARCHAR(45),
    USEYN     CHAR(1),
    CODE_DT   VARCHAR(45),
    CONSTRAINT PK_BARCODE_INFO PRIMARY KEY (SN, CODE_TYPE)
);

CREATE TABLE FILE_OPENER_LIST (
    SN      DECIMAL(6) NOT NULL,
    UUID    VARCHAR(50),
    USE_YN  CHAR(1),
    UPD_DT  DATETIME,
    FILE_SN DECIMAL(20),
    CONSTRAINT PK_FILE_OPENER_LIST PRIMARY KEY (SN)
);

CREATE TABLE SOCKET_MESSAGE (
    SN        DECIMAL(6) NOT NULL,
    UUID      VARCHAR(50),
    MESSAGE   VARCHAR(1000) NOT NULL,
    SENDER    VARCHAR(100),
    USEYN     CHAR(1) DEFAULT 'Y',
    TIMESTAMP VARCHAR(30),
    CONSTRAINT PK_SOCKET_MESSAGE PRIMARY KEY (SN, UUID)
);

CREATE TABLE STREAMING_MEDIA (
    SN         DECIMAL(6) NOT NULL,
    UUID       VARCHAR(50),
    MEDIA_TYPE VARCHAR(20),
    FILE_PATH  VARCHAR(500),
    DURATION   VARCHAR(20),
    USEYN      CHAR(1),
    TIMESTAMP  VARCHAR(30),
    CONSTRAINT PK_STREAMING_MEDIA PRIMARY KEY (SN)
);

CREATE TABLE FACE_MESH_INFO (
    SN             DECIMAL(6) NOT NULL,
    UUID           VARCHAR(50) NOT NULL,
    USEYN          CHAR(1) DEFAULT 'Y',
    TIMESTAMP      VARCHAR(30),
    FACE_GROUP_ID  VARCHAR(50) NOT NULL,
    SOURCE         VARCHAR(20),
    IMAGE_PATH     VARCHAR(500),
    IMAGE_WIDTH    VARCHAR(20),
    IMAGE_HEIGHT   VARCHAR(20),
    FACE_COUNT     VARCHAR(10),
    FACE_INDEX     VARCHAR(10),
    TRACKING_ID    VARCHAR(32),
    BBOX_LEFT      VARCHAR(10),
    BBOX_TOP       VARCHAR(10),
    BBOX_RIGHT     VARCHAR(10),
    BBOX_BOTTOM    VARCHAR(10),
    LANDMARK_COUNT VARCHAR(10),
    MESH_SCORE     VARCHAR(10),
    HAS_IRIS       CHAR(1),
    IOD_NORM       VARCHAR(10),
    NOSE_TIP_X     VARCHAR(10),
    NOSE_TIP_Y     VARCHAR(10),
    LEFT_EYE_X     VARCHAR(10),
    LEFT_EYE_Y     VARCHAR(10),
    RIGHT_EYE_X    VARCHAR(10),
    RIGHT_EYE_Y    VARCHAR(10),
    MOUTH_CENTER_X VARCHAR(10),
    MOUTH_CENTER_Y VARCHAR(10),
    HEAD_EULER_X   VARCHAR(10),
    HEAD_EULER_Y   VARCHAR(10),
    HEAD_EULER_Z   VARCHAR(10),
    CONSTRAINT PK_FACE_MESH_INFO PRIMARY KEY (SN)
);

CREATE TABLE IOT_MESSAGE (
    SN          DECIMAL(6) NOT NULL,
    UUID        VARCHAR(64) NOT NULL,
    TOPIC       VARCHAR(255) NOT NULL,
    PAYLOAD     VARCHAR(2000) NOT NULL,
    DIRECTION   VARCHAR(20) NOT NULL,
