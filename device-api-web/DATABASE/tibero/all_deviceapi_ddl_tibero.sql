-- 테이블 생성
CREATE TABLE COMTECOPSEQ (
    TABLE_NAME VARCHAR2(20) NOT NULL,
    NEXT_ID    NUMBER(30),
    CONSTRAINT PK_COMTECOPSEQ PRIMARY KEY (TABLE_NAME)
);

CREATE TABLE ACCELERATOR (
    SN        NUMBER(6) NOT NULL,
    UUID      VARCHAR2(50) NOT NULL,
    XAXIS     VARCHAR2(20),
    YAXIS     VARCHAR2(20),
    ZAXIS     VARCHAR2(20),
    TIMESTAMP VARCHAR2(20),
    USEYN     CHAR(1),
    CONSTRAINT PK_ACCELERATOR PRIMARY KEY (SN, UUID)
);

CREATE TABLE CONTACT_INFO (
    SN     NUMBER(6) NOT NULL,
    NAME   CHAR(60),
    TELNO  CHAR(20),
    EMAILS VARCHAR2(50),
    USEYN  CHAR(1),
    UUID   VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_CONTACT_INFO PRIMARY KEY (SN, UUID)
);

CREATE TABLE FILE_DETAIL_INFO (
    FILE_SN         NUMBER(20) NOT NULL,
    FILE_STRE_COURS VARCHAR2(2000),
    STRE_FILE_NM    VARCHAR2(255),
    ORIGNL_FILE_NM  VARCHAR2(255),
    FILE_EXTSN      VARCHAR2(20),
    FILE_CN         BLOB,
    FILE_SIZE       NUMBER(8),
    CONSTRAINT PK_FILE_DETAIL_INFO PRIMARY KEY (FILE_SN)
);

CREATE TABLE FILE_READER_WRITE (
    SN         NUMBER(6) NOT NULL,
    UUID       VARCHAR2(50) NOT NULL,
    FILE_NM    VARCHAR2(255),
    FILE_TYPE  VARCHAR2(40),
    UPDT_DT    DATE,
    USEYN      CHAR(1),
    FILE_SN    NUMBER(20) NOT NULL,
    FILE_COURS VARCHAR2(2000),
    FILE_SIZE  VARCHAR2(40),
    CONSTRAINT PK_FILE_READER_WRITE PRIMARY KEY (SN, UUID),
    CONSTRAINT FILE_READER_WRITE_FK1 FOREIGN KEY (FILE_SN) REFERENCES FILE_DETAIL_INFO (FILE_SN)
);

CREATE TABLE MEDIA (
    SN       NUMBER(6) NOT NULL,
    UUID     VARCHAR2(50) NOT NULL,
    MD_CODE  VARCHAR2(40),
    MD_SJ    VARCHAR2(255),
    USEYN    CHAR(1),
    REVIV_CO VARCHAR2(40),
    FILE_SN  NUMBER(20) NOT NULL,
    CONSTRAINT PK_MEDIA PRIMARY KEY (SN, UUID),
    CONSTRAINT MEDIA_FK1 FOREIGN KEY (FILE_SN) REFERENCES FILE_DETAIL_INFO (FILE_SN)
);

CREATE TABLE DEVICE (
    SN                NUMBER(6) NOT NULL,
    UUID              VARCHAR2(50) NOT NULL,
    TELNO             VARCHAR2(15),
    STRGE_INFO        VARCHAR2(40),
    NTWRK_DEVICE_INFO VARCHAR2(20),
    PG_VER            VARCHAR2(40),
    DEVICE_NM         VARCHAR2(200),
    USEYN             CHAR(1),
    OS                VARCHAR2(15),
    CONSTRAINT PK_DEVICE PRIMARY KEY (SN, UUID)
);

CREATE TABLE INTERFACE_EGOV (
    SN      NUMBER(6) NOT NULL,
    UUID    VARCHAR2(50) NOT NULL,
    EMAILS  VARCHAR2(50),
    USER_ID VARCHAR2(20),
    USER_PW VARCHAR2(2000),
    CONSTRAINT PK_INTERFACE_EGOV PRIMARY KEY (SN, UUID)
);

CREATE TABLE COMPASS (
    SN        NUMBER(6) NOT NULL,
    UUID      VARCHAR2(50) NOT NULL,
    DRC       VARCHAR2(40),
    ACCRCY    VARCHAR2(40),
    USEYN     CHAR(1),
    TIMESTAMP VARCHAR2(20),
    CONSTRAINT PK_COMPASS PRIMARY KEY (SN, UUID)
);

CREATE TABLE GPS (
    SN     NUMBER(6) NOT NULL,
    UUID   VARCHAR2(50) NOT NULL,
    LA     VARCHAR2(48),
    LO     VARCHAR2(48),
    ACCRCY VARCHAR2(10),
    USEYN  CHAR(1),
    CONSTRAINT PK_GPS PRIMARY KEY (SN, UUID)
);

CREATE TABLE NETWORK (
    SN         NUMBER(6) NOT NULL,
    UUID       VARCHAR2(50) NOT NULL,
    NTWRK_TYPE VARCHAR2(20),
    USEYN      CHAR(1),
    CONSTRAINT PK_NETWORK PRIMARY KEY (SN, UUID)
);

CREATE TABLE PUSH_DEVICE (
    SN                NUMBER(6) NOT NULL,
    UUID              VARCHAR2(50) NOT NULL,
    NTWRK_DEVICE_INFO VARCHAR2(20),
    OS_VER            VARCHAR2(40),
    DEVICE_NM         VARCHAR2(200),
    USEYN             CHAR(1),
    OS_TYPE           VARCHAR2(15),
    TOKEN_ID          VARCHAR2(500),
    CONSTRAINT PK_PUSH_DEVICE PRIMARY KEY (SN, UUID)
);

CREATE TABLE PUSH_MESSAGE (
    SN       NUMBER(6) NOT NULL,
    UUID     VARCHAR2(50) NOT NULL,
    MESSAGE  VARCHAR2(2000),
    SND_DT   VARCHAR2(20),
    TOKEN_ID VARCHAR2(250) NOT NULL,
    CONSTRAINT PK_PUSH_MESSAGE PRIMARY KEY (SN, UUID, TOKEN_ID)
);

CREATE TABLE BARCODE_INFO (
    SN        NUMBER(6) NOT NULL,
    UUID      VARCHAR2(50),
    CODE_TYPE VARCHAR2(45) NOT NULL,
    CODE_TEXT VARCHAR2(45),
    USEYN     CHAR(1),
    CODE_DT   VARCHAR2(45),
    CONSTRAINT PK_BARCODE_INFO PRIMARY KEY (SN, CODE_TYPE)
);

CREATE TABLE FILE_OPENER_LIST (
    SN      NUMBER(6) NOT NULL,
    UUID    VARCHAR2(50),
    USE_YN  CHAR(1),
    UPD_DT  DATE,
    FILE_SN NUMBER(20),
    CONSTRAINT PK_FILE_OPENER_LIST PRIMARY KEY (SN)
);

CREATE TABLE SOCKET_MESSAGE (
    SN        NUMBER(6) NOT NULL,
    UUID      VARCHAR2(50),
    MESSAGE   VARCHAR2(1000) NOT NULL,
    SENDER    VARCHAR2(100),
    USEYN     CHAR(1) DEFAULT 'Y',
    TIMESTAMP VARCHAR2(30),
    CONSTRAINT PK_SOCKET_MESSAGE PRIMARY KEY (SN, UUID)
);

CREATE TABLE STREAMING_MEDIA (
    SN         NUMBER(6) NOT NULL,
    UUID       VARCHAR2(50),
    MEDIA_TYPE VARCHAR2(20),
    FILE_PATH  VARCHAR2(500),
    DURATION   VARCHAR2(20),
    USEYN      CHAR(1),
    TIMESTAMP  VARCHAR2(30),
    CONSTRAINT PK_STREAMING_MEDIA PRIMARY KEY (SN)
);

CREATE TABLE FACE_MESH_INFO (
    SN             NUMBER(6) NOT NULL,
    UUID           VARCHAR2(50) NOT NULL,
    USEYN          CHAR(1) DEFAULT 'Y',
    TIMESTAMP      VARCHAR2(30),
    FACE_GROUP_ID  VARCHAR2(50) NOT NULL,
    SOURCE         VARCHAR2(20),
    IMAGE_PATH     VARCHAR2(500),
    IMAGE_WIDTH    VARCHAR2(20),
    IMAGE_HEIGHT   VARCHAR2(20),
    FACE_COUNT     VARCHAR2(10),
    FACE_INDEX     VARCHAR2(10),
    TRACKING_ID    VARCHAR2(32),
    BBOX_LEFT      VARCHAR2(10),
    BBOX_TOP       VARCHAR2(10),
    BBOX_RIGHT     VARCHAR2(10),
    BBOX_BOTTOM    VARCHAR2(10),
    LANDMARK_COUNT VARCHAR2(10),
    MESH_SCORE     VARCHAR2(10),
    HAS_IRIS       CHAR(1),
    IOD_NORM       VARCHAR2(10),
    NOSE_TIP_X     VARCHAR2(10),
    NOSE_TIP_Y     VARCHAR2(10),
    LEFT_EYE_X     VARCHAR2(10),
    LEFT_EYE_Y     VARCHAR2(10),
    RIGHT_EYE_X    VARCHAR2(10),
    RIGHT_EYE_Y    VARCHAR2(10),
    MOUTH_CENTER_X VARCHAR2(10),
    MOUTH_CENTER_Y VARCHAR2(10),
    HEAD_EULER_X   VARCHAR2(10),
    HEAD_EULER_Y   VARCHAR2(10),
    HEAD_EULER_Z   VARCHAR2(10),
    CONSTRAINT PK_FACE_MESH_INFO PRIMARY KEY (SN)
);

CREATE TABLE IOT_MESSAGE (
    SN          NUMBER(6) NOT NULL,
    UUID        VARCHAR2(64) NOT NULL,
    TOPIC       VARCHAR2(255) NOT NULL,
    PAYLOAD     VARCHAR2(2000) NOT NULL,
    DIRECTION   VARCHAR2(20) NOT NULL,
    MESSAGETYPE VARCHAR2(20) NOT NULL,
    USEYN       CHAR(1) DEFAULT 'Y',
    TIMESTAMP   VARCHAR2(30),
    CONSTRAINT PK_IOT_MESSAGE PRIMARY KEY (SN, UUID)
);

CREATE TABLE AI_CHAT_INFO (
    SN                 NUMBER(6) NOT NULL,
    UUID               VARCHAR2(50) NOT NULL,
    QUESTION           VARCHAR2(2000) NOT NULL,
    ANSWER             CLOB,
    CHAT_MODE          VARCHAR2(20),
    MODEL_NM           VARCHAR2(100),
    SESSION_ID         VARCHAR2(50),
    USEYN              CHAR(1) DEFAULT 'Y',
    QUESTION_TIMESTAMP VARCHAR2(30),
    ANSWER_TIMESTAMP   VARCHAR2(30),
    CONSTRAINT PK_AI_CHAT_INFO PRIMARY KEY (SN, UUID)
);

